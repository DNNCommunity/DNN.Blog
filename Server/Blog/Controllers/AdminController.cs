using System.Linq;
using System.Web.Mvc;
using DotNetNuke.Modules.Blog.Common;
using DotNetNuke.Modules.Blog.Core.Common;
using DotNetNuke.Modules.Blog.Core.Integration;
using DotNetNuke.Modules.Blog.Models;
using DotNetNuke.Services.Localization;
using DotNetNuke.Web.Mvc.Framework.ActionFilters;
using Microsoft.Extensions.Logging;

namespace DotNetNuke.Modules.Blog.Controllers
{
    [DnnHandleError]
    public class AdminController : BlogMvcController
    {
        private readonly ILogger<AdminController> _logger;

        public AdminController(ILogger<AdminController> logger) : base()
        {
            _logger = logger;
        }

        [HttpGet]
        public ActionResult Index()
        {
            _logger.LogDebug("Admin Index GET by user {UserId}, module {ModuleId}", User.UserID, ModuleContext.ModuleId);
            BlogModuleContext.EnsureInitialized();
            BlogModuleContext.RequirePermissionLevel(BlogModuleContext.Security.IsEditor);
            BlogModuleContext.RegisterAjaxScript();
            BlogModuleContext.AddModuleCss();
            BlogModuleContext.AddScript("blog.js");
            _logger.LogInformation("Admin settings page rendered for module {ModuleId}", ModuleContext.ModuleId);
            return View(BuildViewModel());
        }

        [HttpPost]
        [ValidateInput(false)]
        [Web.Api.ValidateAntiForgeryToken]
        public ActionResult Index(ModuleSettings settings)
        {
            _logger.LogDebug("Admin Index POST by user {UserId}, module {ModuleId}", User.UserID, ModuleContext.ModuleId);
            BlogModuleContext.RequirePermissionLevel(BlogModuleContext.Security.IsEditor);

            var current = BlogModuleContext.Settings;
            current.AllowAttachments = settings.AllowAttachments;
            current.SummaryModel = settings.SummaryModel;
            current.AllowMultipleCategories = settings.AllowMultipleCategories;
            current.AllowWLW = settings.AllowWLW;
            current.WLWRecentPostsMax = settings.WLWRecentPostsMax;
            current.VocabularyId = settings.VocabularyId;
            current.ModifyPageDetails = settings.ModifyPageDetails;
            current.AutoGenerateMissingSummary = settings.AutoGenerateMissingSummary;
            current.AutoGeneratedSummaryLength = settings.AutoGeneratedSummaryLength;
            current.RssAllowContentInFeed = settings.RssAllowContentInFeed;
            current.RssDefaultCopyright = settings.RssDefaultCopyright ?? "";
            current.RssDefaultNrItems = settings.RssDefaultNrItems;
            current.RssEmail = settings.RssEmail ?? "";
            current.RssImageHeight = settings.RssImageHeight;
            current.RssImageWidth = settings.RssImageWidth;
            current.RssImageSizeAllowOverride = settings.RssImageSizeAllowOverride;
            current.RssMaxNrItems = settings.RssMaxNrItems;
            current.RssTtl = settings.RssTtl;
            current.IncrementViewCount = settings.IncrementViewCount;
            var editorMode = (settings.EditorMode ?? "html").Trim().ToLowerInvariant();
            current.EditorMode = editorMode == "markdown" ? "markdown" : "html";
            current.SaveSettings();

            _logger.LogInformation("Admin settings saved for module {ModuleId}: vocabulary {VocabularyId}, editorMode {EditorMode}",
                ModuleContext.ModuleId, current.VocabularyId, current.EditorMode);
            return Redirect(Url.Action("Index", "Admin"));
        }

        [HttpPost]
        [Web.Api.ValidateAntiForgeryToken]
        public ActionResult CreateVocabulary()
        {
            _logger.LogDebug("CreateVocabulary requested by user {UserId}, module {ModuleId}", User.UserID, ModuleContext.ModuleId);
            BlogModuleContext.RequirePermissionLevel(BlogModuleContext.Security.IsEditor);
            var settings = BlogModuleContext.Settings;
            settings.VocabularyId = Integration.CreateNewVocabulary(PortalSettings.PortalId).VocabularyId;
            settings.SaveSettings();
            _logger.LogInformation("Created vocabulary {VocabularyId} for module {ModuleId}", settings.VocabularyId, ModuleContext.ModuleId);
            return Redirect(Url.Action("Index", "Admin"));
        }

        private AdminViewModel BuildViewModel()
        {
            var settings = BlogModuleContext.Settings;

            var vocabularies = Globals.GetPortalVocabularies(PortalSettings.PortalId)
                .Select(v => new SelectListItem
                {
                    Text = v.Name,
                    Value = v.VocabularyId.ToString(),
                    Selected = v.VocabularyId == settings.VocabularyId
                })
                .ToList();
            vocabularies.Insert(0, new SelectListItem
            {
                Text = "None",
                Value = "-1",
                Selected = settings.VocabularyId <= -1
            });

            var locales = LocaleController.Instance.GetLocales(PortalSettings.PortalId).Values
                .Where(l => l.Code != PortalSettings.DefaultLanguage)
                .OrderBy(l => l.Code)
                .ToList();
            bool multiLingual = LocaleController.Instance.GetLocales(PortalSettings.PortalId).Count > 1;

            return new AdminViewModel
            {
                Settings = settings,
                Vocabularies = vocabularies,
                ShowMultilingualLinks = multiLingual,
                HasVocabulary = settings.VocabularyId > -1,
                DefaultLocale = PortalSettings.DefaultLanguage,
                Locales = locales
            };
        }
    }
}
